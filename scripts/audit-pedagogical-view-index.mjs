import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const viewsRoot = path.join(root, 'public', 'knowledge', 'pedagogical', 'views');
const outputPath = path.join(root, 'src', 'data', 'pedagogicalViewIndex.generated.ts');

const files = fs.readdirSync(viewsRoot)
  .filter((name) => /^IP-A\d{2}-(?:G|S)\d{2}\.json$/.test(name))
  .sort((left, right) => left.localeCompare(right));

if (files.length !== 115) {
  throw new Error(`View index incompleto: ${files.length}/115 arquivos.`);
}

const entries = files.map((name) => {
  const filePath = path.join(viewsRoot, name);
  const view = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const id = name.replace(/\.json$/, '');
  const sourceId = view.unit?.unitId || view.source?.unitId;
  if (sourceId !== id) throw new Error(`${id}: unitId divergente (${sourceId}).`);
  if (!view.unit?.title) throw new Error(`${id}: título ausente.`);
  if (!(view.viewSchemaVersion === '1.0.0' || String(view.viewSchemaVersion).startsWith('4.2.'))) {
    throw new Error(`${id}: viewSchemaVersion não suportada (${view.viewSchemaVersion}).`);
  }

  return {
    unitId: id,
    lessonId: view.unit.lessonId || view.source?.lessonId || id.slice(3, 6),
    title: view.unit.title,
    learningObjectives: Array.isArray(view.unit.learningObjectives)
      ? view.unit.learningObjectives.filter(Boolean)
      : view.unit.objective
        ? [view.unit.objective]
        : [],
    unitType: view.unitType === 'cumulative_review' ? 'cumulative_review' : 'regular',
    viewSchemaVersion: view.viewSchemaVersion,
  };
});

const regularCount = entries.filter((entry) => entry.unitType === 'regular').length;
const cumulativeCount = entries.filter((entry) => entry.unitType === 'cumulative_review').length;
if (regularCount !== 102 || cumulativeCount !== 13) {
  throw new Error(`Distribuição inválida: ${regularCount} regulares, ${cumulativeCount} cumulativas.`);
}

const source = `/* AUTO-GENERATED by scripts/build-pedagogical-view-index.mjs. */
export interface PedagogicalViewIndexEntry {
  unitId: string;
  lessonId: string;
  title: string;
  learningObjectives: string[];
  unitType: 'regular' | 'cumulative_review';
  viewSchemaVersion: string;
}

export const PEDAGOGICAL_VIEW_INDEX = ${JSON.stringify(entries, null, 2)} as const satisfies readonly PedagogicalViewIndexEntry[];

export const PEDAGOGICAL_VIEW_BY_ID = Object.fromEntries(
  PEDAGOGICAL_VIEW_INDEX.map((entry) => [entry.unitId, entry]),
) as Record<string, PedagogicalViewIndexEntry>;
`;

const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
if (current !== source) throw new Error('Published view index differs from published views. Restore the matching release; editorial generation is external.');
console.log('Pedagogical view index contract: PASS');
